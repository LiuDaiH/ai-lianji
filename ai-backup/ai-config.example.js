//
// 【在哪找】
//   微信开发者工具 → 顶部「云开发」→ 环境列表里那个 ID
//
// 【为什么明写在代码里是安全的】
//   ① 环境 ID 不是密钥，只是个标识符。微信官方文档的示例就是明文写法：
//        wx.cloud.init({ env: "your-env-id" });
//   ② 别人就算从你的小程序包里翻出这个 ID，也调不动你的云资源 ——
//      因为 wx.cloud 的鉴权绑的是你的 AppID + 用户身份，跨小程序无法复用。
//   ③ 真正的密钥（API Key / SecretKey）由微信云开发平台托管，
//      根本不会下发到小程序前端。这也是本方案不用"直连大模型 API"的原因。
//
// 【为什么必须内置（不能只靠用户在界面上填）】
//   界面上填的值存在 wx.setStorageSync（设备本地）。
//   换设备、或用真机打开时，本地存储是空的 → AI 会突然"消失"。
//   内置进代码才能保证模拟器、真机、所有用户都能用。
//
// 【会暴露给用户吗】
//   不会。小程序界面【不显示】这里填的值，用户只会看到
//   「已就绪（使用应用内置的 AI 环境）」，看不到具体 ID。
//   用户也可以填自己的 ID 覆盖，或者直接关掉 AI 退回本地算法。
//
// 【优先级】
//   用户在小程序「关于这个工具」页手动填的  >  这里内置的
//   （所以就算内置了，用户在界面上改也能覆盖）

